#!/usr/bin/env node
/** Derive additional variants from the checked-in prototype's canonical rules. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";
import postcss from "postcss";

const args = process.argv.slice(2);
const bundleArg = args.indexOf("--bundle");
const bundlePath = bundleArg >= 0
  ? resolve(args[bundleArg + 1])
  : fileURLToPath(new URL("../src/prototype-utilities.css", import.meta.url));
const marker = "/* Generated by scripts/sync-prototype-utilities.mjs; do not edit this layer. */";
const current = readFileSync(bundlePath, "utf8");
const canonical = current.split(marker)[0].trimEnd();
const source = postcss.parse(canonical);
const layer = postcss.atRule({ name: "layer", params: "utilities" });
const hover = postcss.atRule({ name: "media", params: "(hover:hover)" });
const escapeClass = (token) => token.replace(/[.,:/[\]()%#]/g, (character) => `\\${character}`);

for (const color of ["action-sky", "status-error"]) {
  const baseSelector = `.${escapeClass(`border-${color}/30`)}`;
  const variantSelector = `.${escapeClass(`disabled:hover:border-${color}/30`)}:disabled:hover`;
  let copies = 0;
  source.walkRules((rule) => {
    if (rule.selector !== baseSelector) return;
    // Carry the original fallback and any conditional color-mix rule together.
    // The bundle remains authoritative for both the palette and browser support.
    let copy = rule.clone({ selector: variantSelector });
    for (let parent = rule.parent; parent && parent.type !== "root"; parent = parent.parent) {
      if (parent.type === "atrule" && parent.name === "layer") break;
      if (parent.type !== "atrule") throw new Error(`Unexpected parent for ${baseSelector}`);
      const wrapper = parent.clone({ nodes: [] });
      wrapper.append(copy);
      copy = wrapper;
    }
    hover.append(copy);
    copies += 1;
  });
  if (!copies) throw new Error(`Canonical utility missing: ${baseSelector}`);
}
layer.append(hover);
const output = `${canonical}\n${marker}\n${layer.toString()}\n`;
if (args.includes("--check")) {
  if (current !== output) throw new Error("Prototype variants are stale; run npm run utilities:sync.");
} else {
  writeFileSync(bundlePath, output);
}
